from fastapi import APIRouter, BackgroundTasks, HTTPException, UploadFile, File, Form, Depends
from typing import Optional
import os
import shutil
from pathlib import Path

from app.config import settings
from app.database.connection import get_database
from app.services.live_analyzer import (
    create_session,
    get_session,
    get_active_session,
    stop_all_sessions,
    get_live_analyzer,
)

router = APIRouter(prefix="/api/live", tags=["live"])

@router.post("/start")
async def start_live_session(
    background_tasks: BackgroundTasks,
    bus_id: str = Form(...),
    file: UploadFile = File(None),
    use_demo_video: bool = Form(False),
):
    """
    Start a live analysis session.
    For the prototype, this takes an uploaded video or uses a default demo video
    to simulate a live camera feed.
    """
    stop_all_sessions()  # Only one active live session for the demo

    if use_demo_video:
        # Provide a fallback path or expect one in the uploads dir
        video_path = os.path.join(settings.UPLOAD_DIR, "demo_live.mp4")
        if not os.path.exists(video_path):
            raise HTTPException(status_code=404, detail="Demo video not found on server")
    elif file:
        video_path = os.path.join(settings.UPLOAD_DIR, file.filename)
        with open(video_path, "wb") as buffer:
            shutil.copyfileobj(file.file, buffer)
    else:
        raise HTTPException(status_code=400, detail="Must provide video file or set use_demo_video=true")

    session_id = create_session(bus_id, video_path)
    
    db = get_database()
    analyzer = get_live_analyzer()
    
    # Run the session in the background
    background_tasks.add_task(analyzer.run_session, session_id, video_path, bus_id, db)
    
    return {"session_id": session_id, "status": "started"}

@router.post("/stop")
async def stop_live_session():
    """Stop all active live sessions."""
    stop_all_sessions()
    return {"status": "stopped"}

@router.get("/status")
async def get_live_status():
    """
    Poll this endpoint to get the current state of the live session.
    Returns current frame, detections, risk, and warnings.
    """
    session = get_active_session()
    if not session:
        return {"active": False, "status": "no active session"}
    
    return {
        "active": session.get("active"),
        "status": session.get("status"),
        "bus_id": session.get("bus_id"),
        "frame_count": session.get("frame_count"),
        "latest_frame": session.get("latest_frame"), # Base64 encoded image
        "latest_detections": session.get("latest_detections"),
        "latest_risk": session.get("latest_risk"),
        "latest_traffic": session.get("latest_traffic"),
        "latest_gps": session.get("latest_gps"),
        "latest_warning": session.get("latest_warning"),
        "route_recommendation": session.get("route_recommendation"),
        "error": session.get("error"),
        "last_updated": session.get("last_updated"),
    }

@router.get("/warnings")
async def get_live_warnings(limit: int = 10):
    """Get the recent warnings generated by the live session."""
    session = get_active_session()
    if not session:
        return {"warnings": []}
    
    warnings_list = list(session.get("warnings", []))
    return {"warnings": warnings_list[:limit]}
